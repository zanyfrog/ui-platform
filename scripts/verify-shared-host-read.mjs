import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { applicationComposition } from '../packages/visual-artifacts/dist/vite.js';
const ev=path.resolve('evidence/v1-shared-composition-20261029');
const run=(await fs.readdir(ev)).filter(p=>p.startsWith('run-')).sort().at(-1);
if(!run) throw Error('Run the detached service fixture first');
const fixture=path.join(ev,run,'fixture'),root=path.join(fixture,'apps/fixture'),shared=path.join(fixture,'components');
await fs.writeFile(path.join(root,'package.json'),'{}');
await fs.writeFile(path.join(root,'app.manifest.json'),'{"appId":"fixture"}');
const plugin=applicationComposition({root,sharedComponentsRoot:shared});
plugin.configResolved({command:'serve'});
const capture=()=>plugin.load.call({addWatchFile(){},resolve(){throw Error('Unexpected helper dependency');}},'\0virtual:uip-application-composition');
const code=await capture(); assert.ok(code.includes('registerManagedVisualGraph')); assert.ok(code.includes('region-main'));
const refusals=[];
for(const owner of [path.join(root,'src/pages'),path.join(root,'shells'),shared,path.join(root,'presentation/platform-components')]) {
  const transaction=path.join(owner,'.uib/transactions','a'.repeat(64));
  await fs.mkdir(transaction,{recursive:true});
  const journal=path.join(transaction,'pending.json');
  const bytes='UNINTERPRETABLE_PENDING_JOURNAL_MUST_NOT_BE_READ_OR_REPLAYED';
  await fs.writeFile(journal,bytes);
  await assert.rejects(capture(),/recovery|Recovery|incomplete|transaction/i);
  assert.equal(await fs.readFile(journal,'utf8'),bytes);
  await fs.unlink(journal);
  refusals.push({owner,refused:true,journalUnchanged:true});
}
assert.ok((await capture()).includes('registerManagedVisualGraph'));
const packageRoot=path.join(fixture,'native-contracts');await fs.mkdir(packageRoot,{recursive:true});
const installed=JSON.parse(await fs.readFile('node_modules/@ui-base/ui/ui.component.json','utf8'));
await fs.writeFile(path.join(packageRoot,'ui.component.json'),JSON.stringify({components:installed.components.filter(c=>['uib-card','uib-panel'].includes(c.tagName))}));
await fs.writeFile(path.join(packageRoot,'package.json'),'{"name":"@ui-base/ui"}');
const packageManifest=path.join(packageRoot,'ui.component.json');
const explicit=applicationComposition({root,sharedComponentsRoot:shared,packageManifests:[packageManifest]});explicit.configResolved({command:'serve'});
const explicitCode=await explicit.load.call({addWatchFile(){}},'\0virtual:uip-application-composition');
assert.ok(explicitCode.includes('@ui-base/ui:uib-panel'),'legacy package identity uses installed package name');
assert.ok(explicitCode.includes('cmp_platform_5d42b928-83bf-4b18-a4c0-48b06c2efa1'),'Card identity retained');
const duplicate=applicationComposition({root,sharedComponentsRoot:shared,packageManifests:[packageManifest,packageManifest]});duplicate.configResolved({command:'serve'});
await assert.rejects(duplicate.load.call({addWatchFile(){}},'\0virtual:uip-application-composition'),/Duplicate explicit/);
await fs.writeFile(path.join(ev,run,'host-read-result.json'),JSON.stringify({passed:true,actualPlugin:true,actualFoundationRecoveryRefusal:true,cleanCapture:true,explicitNativeContracts:true,duplicateContractRefusal:true,refusals,scope:'Detached physical fixture roots only; generated native import strings are not executed. No website host launch or live journal manipulation'},null,2));
console.log('PASS host source-read '+run);
