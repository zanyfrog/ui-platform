import { afterEach, expect, it } from 'vitest';
import { createServer } from 'vite';
import { createServer as httpServer } from 'node:http';
import { createRequire } from 'node:module';
import { readFile, mkdtemp, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { startFormReference, closeFormReference } from '../scripts/form-reference-host.js';
import { VisualArtifactService } from '../src/server/visual-artifacts.js';
import { effectiveField, formPayload, formValueErrors, generateForm, resolveMode, validateArtifact, moveNode } from '@ui-platform/visual-artifacts';
import type { ArtifactMetadata, DatasetDefinition } from '@ui-platform/visual-artifacts';
const schema = JSON.parse(await readFile('references/form-data/person.dataset.json', 'utf8')) as DatasetDefinition;
const metadata = JSON.parse(await readFile('components/person-form/component.visual.json', 'utf8')) as ArtifactMetadata;
const close: Array<() => Promise<unknown>> = [];
afterEach(async () => { for (const fn of close.splice(0).reverse()) await fn(); await closeFormReference(); });

it('creates both Form paths through VisualArtifactService and preserves source authority', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'form-source-')); close.push(() => rm(root, { recursive: true, force: true }));
  const service = new VisualArtifactService(root, 'component');
  const generated = await service.create('person', undefined, { dataset: schema });
  expect(generated.metadata?.componentId).toMatch(/^cmp_platform_/);
  expect(generated.metadata?.form?.fields.map(f => f.key)).toEqual(['firstName', 'lastName', 'email', 'status', 'internalNotes']);
  expect((await service.list())[0].metadata?.capabilities).toContain('form');
  const blank = await service.create('blank', undefined, {});
  expect(blank.metadata?.form?.fields).toEqual([]);
  expect(validateArtifact({ metadata: blank.metadata!, source: blank.files.source, css: '' }).some(d => d.message.includes('Dataset target'))).toBe(true);
  const reordered = moveNode(generated.files.source, 'row_lastName', 'up');
  expect(reordered.indexOf('row_lastName')).toBeLessThan(reordered.indexOf('row_firstName'));
  const saved = await service.save(generated.locator, 'source', reordered, generated.hash);
  await expect(service.save(generated.locator, 'source', 'stale', generated.hash)).rejects.toThrow('changed on disk');
  expect((await service.read(generated.locator)).files.source).toBe(saved.files.source);
});
it('keeps host restrictions independent from modes and preserves denied values outside payloads', () => {
  const m = structuredClone(metadata), overrides = resolveMode(m, 'admin');
  expect(resolveMode(m).control_status.visible).toBe(false);
  expect(overrides.control_status.visible).toBe(true);
  expect(() => resolveMode(m, 'unknown')).toThrow('Unknown mode');
  const original = { id: 'one', firstName: 'Ada', lastName: 'Lovelace', email: 'ada@example.test', status: 'active', internalNotes: 'preserve' };
  const values = { ...original, firstName: 'Augusta', internalNotes: 'crafted' };
  const fields = m.form!.fields.map(f => effectiveField(f, overrides, 'edit', false, f.key === 'internalNotes' ? { write: false } : undefined));
  expect(formPayload(m, values, original, fields, 'edit')).toEqual({ id: 'one', firstName: 'Augusta' });
  expect(values.internalNotes).toBe('crafted');
  expect(formValueErrors({ ...values, firstName: '' }, fields)).toHaveProperty('field_person-firstName');
  m.modes!.overrides.admin.control_firstName = { required: false };
  expect(validateArtifact({ metadata: m, source: generateForm(structuredClone(metadata), schema).source, css: '' }).some(d => d.message.includes('cannot weaken'))).toBe(true);
});

it('renders routed public/admin reuse, persists create/read/update through V1 identity and protected DOE, and rejects crafted fields', async () => {
  const probe = httpServer(); await new Promise<void>(resolve => probe.listen(0, '127.0.0.1', resolve));
  const port = (probe.address() as { port: number }).port; await new Promise<void>(resolve => probe.close(() => resolve()));
  const host = await startFormReference(port);
  const vite = await createServer({ configFile: 'references/form-data/vite.config.ts', server: { port, strictPort: true, proxy: { '/api': { target: host.origin } } } });
  await vite.listen(); close.push(() => vite.close());
  const uiOrigin = vite.resolvedUrls!.local[0].replace(/\/$/, '');
  let playwright; try { playwright = createRequire(import.meta.url)('playwright'); } catch { playwright = createRequire(path.resolve('../ui-base/package.json'))('playwright'); }
  const browser = await playwright.chromium.launch({ headless: true, channel: 'msedge' }); close.push(() => browser.close());
  const page = await browser.newPage();
  const errors: string[] = []; page.on('pageerror', (error: Error) => errors.push(String(error)));
  await page.goto(uiOrigin + '/people/register');
  await page.getByRole('button', { name: 'Sign in as development admin' }).click();
  await page.getByText('Development admin signed in').waitFor({ timeout: 45000 });
  await page.getByLabel('firstName', { exact: true }).fill('Ada');
  await page.getByLabel('lastName', { exact: true }).fill('Lovelace');
  await page.getByLabel('email', { exact: true }).fill('ada@example.test');
  expect(await page.locator('[data-uip-node="control_status"]').isVisible()).toBe(false);
  await page.getByRole('button', { name: 'Submit', exact: true }).click();
  await page.locator('[data-uip-node="saved-result"]').filter({ hasText: 'Ada' }).waitFor({ timeout: 45000 }).catch(async (error: Error) => { throw new Error(String(error) + '\nForm error: ' + await page.locator('[data-uip-node="submit-error"]').innerText() + '\nSaved info: ' + JSON.stringify(await page.locator('[data-uip-node="saved-result"]').evaluate((e: HTMLElement) => ({connected:e.isConnected,host:(e.getRootNode() as ShadowRoot).host.outerHTML,text:e.textContent,html:e.outerHTML,display:getComputedStyle(e).display,rect:e.getBoundingClientRect().toJSON(),parent:e.parentElement?.outerHTML}))) + '\nBrowser errors: ' + errors.join('\n')); });
  const saved = JSON.parse(await page.locator('[data-uip-node="saved-result"]').innerText());
  expect(await readFile(path.join(host.ormData, `${'dev-v1-identity-fixture'}__default__people.json`), 'utf8')).toContain('Ada');
  await page.goto(uiOrigin + `/people/${saved.id}/edit`);
  await expect.poll(() => page.getByLabel('firstName', { exact: true }).inputValue(), { timeout: 45000 }).toBe('Ada').catch(async (e: Error) => { throw new Error(String(e) + '\nErrors: ' + errors.join('\n') + '\nForm error: ' + await page.locator('[data-uip-node="submit-error"]').innerText()); });
  await page.getByLabel('firstName', { exact: true }).fill('Augusta');
  await page.getByLabel('status', { exact: true }).fill('active');
  await page.getByRole('button', { name: 'Submit', exact: true }).click();
  await page.locator('[data-uip-node="saved-result"]').filter({ hasText: 'Augusta' }).waitFor({ timeout: 45000 }).catch(async (e: Error) => { throw new Error(String(e) + await page.locator('[data-uip-node="submit-error"]').innerText()); });
  const dataFile = path.join(host.ormData, 'dev-v1-identity-fixture__default__people.json');
  const beforeDenied = await readFile(dataFile, 'utf8');
  expect(beforeDenied).toContain('Augusta');
  const denied = await page.evaluate(async (id: string) => fetch('/api/application-data/operations', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ datasetId: 'dataset-person-form-reference', operation: 'update', records: [{ id, internalNotes: 'prohibited' }] }) }).then(r => r.json()), saved.id);
  expect(denied).toMatchObject({ success: false, committed: false });
  expect(await readFile(dataFile, 'utf8')).toBe(beforeDenied);
  const invalid = await page.evaluate(async () => fetch('/api/application-data/operations', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ datasetId: 'dataset-person-form-reference', operation: 'insert', records: [{ id: 'missing-required', firstName: 'Invalid' }] }) }).then(r => r.json()));
  expect(invalid).toMatchObject({ success: false, committed: false });
  expect(await readFile(dataFile, 'utf8')).toBe(beforeDenied);
  await page.goto(uiOrigin + `/people/${saved.id}/edit`);
  await expect.poll(() => page.getByLabel('firstName', { exact: true }).inputValue(), { timeout: 45000 }).toBe('Augusta');
  expect(errors).toEqual([]);
  await page.goto(uiOrigin + '/checks.html');
  await page.waitForFunction(() => document.body.dataset.result, { timeout: 30000 });
  expect(await page.locator('#results').innerText()).not.toContain('FAIL:');
  expect(await page.locator('body').getAttribute('data-result')).toBe('passed');
  if (process.env.UI_PLATFORM_WP4_EVIDENCE_ROOT) await writeFile(path.resolve(process.env.UI_PLATFORM_WP4_EVIDENCE_ROOT, 'renderer-checks.txt'), await page.locator('#results').innerText());
}, 180_000);
